# Store original method
original_process_batch = DetectionValidator._process_batch

mode = "GLOBAL"
detector = None

def get_predictions(im_files, ratio_pads):
    preds_list = []
    for i, im_file in enumerate(im_files):
        img = cv2.imread(im_file)
        
        if mode == "GLOBAL":
            preds = detector.predict(img, trigger_conf=-1.0, pure_tiled=False)
        elif mode == "TILED":
            preds = detector.predict(img, trigger_conf=2.0, pure_tiled=True)
        elif mode == "HYBRID":
            preds = detector.predict(img, trigger_conf=0.15, pure_tiled=False)
            
        ratio, (pad_w, pad_h) = ratio_pads[i]
        
        boxes_640 = []
        for p in preds:
            x1, y1, x2, y2 = p["bbox"]
            x1 = x1 * ratio[0] + pad_w
            x2 = x2 * ratio[0] + pad_w
            y1 = y1 * ratio[1] + pad_h
            y2 = y2 * ratio[1] + pad_h
            boxes_640.append([x1, y1, x2, y2, p["detector_confidence"], p["class"]])
            
        if len(boxes_640) > 0:
            pred_tensor = torch.tensor(boxes_640, device='cuda')
        else:
            pred_tensor = torch.zeros((0, 6), device='cuda')
            
        preds_list.append(pred_tensor)
    return preds_list

def custom_update_metrics(self, preds, batch):
    # Ignore preds generated by standard model!
    # Generate our own preds using the image paths in the batch
    custom_preds = get_predictions(batch["im_file"], batch["ratio_pad"])
    
    for si, pred in enumerate(custom_preds):
        self.seen += 1
        pbatch = self._prepare_batch(si, batch)
        cls = pbatch["cls"].cpu().numpy()
        
        predn = self._prepare_pred(pred)
        
        no_pred = predn["cls"].shape[0] == 0
        self.metrics.update_stats(
            {
                **original_process_batch(self, predn, pbatch),
                "target_cls": cls,
                "target_img": np.unique(cls),
                "conf": np.zeros(0) if no_pred else predn["conf"].cpu().numpy(),
                "pred_cls": np.zeros(0) if no_pred else predn["cls"].cpu().numpy(),
                "im_name": Path(pbatch["im_file"]).name,
            }
        )

# Monkey patch update_metrics!
from ultralytics.models.yolo.detect.val import DetectionValidator
DetectionValidator.update_metrics = custom_update_metrics

